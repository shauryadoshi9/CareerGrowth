// Universal translation function: supports keys OR direct English phrases
export function t(keyOrText: string, lang: Language): string {
  if (!keyOrText) return '';
  if (lang === 'en') return keyOrText;

  // 1. Direct dictionary key match
  if (i18nDictionary[keyOrText] && i18nDictionary[keyOrText][lang]) {
    return i18nDictionary[keyOrText][lang];
  }

  // 2. Exact or normalized phrase match
  const norm = normalizePhrase(keyOrText);
  if (phraseMap[norm] && phraseMap[norm][lang]) {
    return phraseMap[norm][lang];
  }

  // 3. Fallback to English in dictionary if present
  if (i18nDictionary[keyOrText] && i18nDictionary[keyOrText]['en']) {
    return i18nDictionary[keyOrText]['en'];
  }

  // 4. Return original text as fallback
  return keyOrText;
}

// Global text node DOM translator
const originalTextCache = new WeakMap<Node, string>();

export function applyDomTranslations(root: HTMLElement = document.body, lang: Language) {
  if (!root || typeof document === 'undefined') return;

  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        const tag = parent.tagName.toLowerCase();
        if (tag === 'script' || tag === 'style' || tag === 'code' || tag === 'pre' || tag === 'textarea') {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  let currentNode = walker.nextNode();
  while (currentNode) {
    let original = originalTextCache.get(currentNode);
    if (original === undefined) {
      original = currentNode.nodeValue || '';
      originalTextCache.set(currentNode, original);
    }

    if (lang === 'en') {
      if (currentNode.nodeValue !== original) {
        currentNode.nodeValue = original;
      }
    } else {
      const trimmed = original.trim();
      const translated = t(trimmed, lang);
      if (translated && translated !== trimmed) {
        const leading = original.match(/^\s*/)?.[0] || '';
        const trailing = original.match(/\s*$/)?.[0] || '';
        currentNode.nodeValue = `${leading}${translated}${trailing}`;
      }
    }
    currentNode = walker.nextNode();
  }
}

